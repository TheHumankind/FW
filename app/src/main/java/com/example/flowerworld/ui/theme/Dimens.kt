package com.example.flowerworld.ui.theme

import androidx.compose.ui.unit.dp

/** Spacing shared by several screens and components. */
object Dimens {
    /** Left and right padding of a full-screen form or a centered column. */
    val ScreenHorizontalPadding = 32.dp

    /** Padding around scrolling lists. */
    val ListPadding = 16.dp

    /** Gap between list items. */
    val ListItemSpacing = 12.dp

    /** Corner radius of buttons, fields and photo areas. */
    val ControlCornerRadius = 2.dp
}
